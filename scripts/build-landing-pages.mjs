export function renderAll() {
  const out = new Map();
  for (const app of Object.values(APPS)) for (const lang of ["en", "zh"]) out.set(pageFile(app, lang), renderLanding(app, lang));
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let changed = 0;
  for (const [file, html] of renderAll()) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === html) continue;
    if (check) throw new Error(`${path.relative(root, file)} is out of date; run node scripts/build-landing-pages.mjs`);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
    changed++;
  }
  console.log(check ? "Landing pages: check passed (6 pages)." : `Landing pages: ${changed} files written.`);
}
