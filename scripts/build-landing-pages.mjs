#!/usr/bin/env node
// Generate the app landing pages (English + Traditional Chinese) from scripts/lib/landing-content.mjs.
//   /tw-stocks/  /us-stocks/  /options/   and   /zh/tw-stocks/  /zh/us-stocks/  /zh/options/
// installUrl in JSON-LD is the clean store URL (no campaign). Store links come from assets/store-links.js; run with --check to verify committed files are current.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { APPS, UI, DISCLAIMER } from "./lib/landing-content.mjs";
import { StoreLinks } from "./lib/store-links.mjs";
import { esc } from "./lib/home-html.mjs";

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ORIGIN = "https://dappgo.com";
const GA_ID = "G-C9K7KCERPP";

export const pagePath = (app, lang) => (lang === "zh" ? `/zh/${app.slug}/` : `/${app.slug}/`);
export const pageFile = (app, lang) => path.join(root, pagePath(app, lang).slice(1), "index.html");
const campaignPage = (app, lang) => (lang === "zh" ? `zh-${app.page}` : app.page);

function badges(app, lang, position) {
  const ui = UI[lang];
  const page = campaignPage(app, lang);
  const link = (os, img, alt, w) =>
    `<a class="badge" data-store="${os}" data-store-position="${position}" href="${esc(StoreLinks.storeUrl(os, app.store, page, position))}" target="_blank" rel="noopener noreferrer"><img src="/assets/store-badges/${img}" alt="${esc(alt)}" width="${w}" height="44" /></a>`;
  return `<div class="store-downloads" aria-label="${esc(app.en.brand)} downloads">${link("ios", "app-store-official.svg", ui.appStoreAlt, 132)}${link("android", "google-play-official.svg", ui.playAlt, 149)}</div>`;
}

function phone(app, lang) {
  const ui = UI[lang];
  const alt = `${app[lang].brand} ${ui.phoneAlt}`;
  const shot = app.phone;
  if (shot.srcset) {
    const { srcset, width, height } = shot;
    return `<figure class="phone" data-reveal><div class="phone-frame"><img src="${srcset}-660.webp" srcset="${srcset}-330.webp 330w, ${srcset}-660.webp 660w, ${srcset}-1320.webp 1320w" sizes="(max-width: 700px) 62vw, 260px" width="${width}" height="${height}" alt="${esc(alt)}" /></div></figure>`;
  }
  const { width, height } = shot;
  return `<figure class="phone" data-reveal><div class="phone-frame"><img src="${shot.src.replace("{lang}", lang)}" width="${width}" height="${height}" alt="${esc(alt)}" /></div></figure>`;
}

function otherApps(app, lang) {
  const ui = UI[lang];
  const items = Object.values(APPS).filter((a) => a.slug !== app.slug).map((a) => `
          <li data-reveal><a class="more-app" href="${pagePath(a, lang)}"><img src="${a.icon}" alt="" width="48" height="48" /><span><b>${esc(a[lang].brand)}</b><small>${esc(a[lang].subtitle)}</small></span><span aria-hidden="true">→</span></a></li>`).join("");
  return `<ul class="more-apps">${items}
        </ul>`;
}

