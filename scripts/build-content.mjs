#!/usr/bin/env node
// Build the reading pages: the daily-report archive (/reports/…), the guides and the about/policy pages,
// in English and Traditional Chinese, plus their block in sitemap.xml.
//   node scripts/build-content.mjs            render everything from data/reports/ and scripts/lib/guides-content.mjs
//   node scripts/build-content.mjs --latest   first archive the latest hash-verified payload of each market, then render
//   node scripts/build-content.mjs --check    fail if any committed page or the sitemap block is out of date (no network)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { esc, localPath, ORIGIN, renderPage, UI } from "./lib/content-shell.mjs";
import { PAGES } from "./lib/guides-content.mjs";
import { renderDay, renderHub, renderMarketIndex } from "./lib/report-render.mjs";
import { extract } from "./lib/report-extract.mjs";

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MARKETS = ["us", "tw", "options"];
const LANGS = ["en", "zh"];
const SITEMAP_START = "    <!-- content:start (generated by scripts/build-content.mjs) -->";
const SITEMAP_END = "    <!-- content:end -->";
const fileFor = (lang, enPath) => path.join(root, localPath(lang, enPath).slice(1), "index.html");

export function loadRecords(base = root) {
  const byMarket = {};
  for (const market of MARKETS) {
    const dir = path.join(base, "data/reports", market);
    const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort() : [];
    byMarket[market] = files.map((f) => {
      const record = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
      if (record.market !== market || `${record.session_date}.json` !== f) throw new Error(`data/reports/${market}/${f}: market or session does not match its path`);
      if (!/^[a-f0-9]{64}$/.test(record.data_hash || "") || !record.generated_at_utc) throw new Error(`data/reports/${market}/${f}: missing data_hash or generated_at_utc`);
      return record;
    });
  }
  return byMarket;
}

function guidePage(lang, page) {
  const c = page[lang];
  const p = (target) => localPath(lang, target);
  const ui = UI[lang];
  const home = { name: ui.home, href: p("/") };
  const crumbs = page.section === "guides"
    ? page.hub ? [home, { name: ui.guides }] : [home, { name: ui.guides, href: p("/guides/") }, { name: c.h1 }]
    : [home, { name: c.h1 }];
  const head = `      <header class="doc-head">
        <p class="doc-kicker">${esc(c.kicker)}</p>
        <h1>${esc(c.h1)}</h1>
        <p class="doc-lede">${esc(c.lede)}</p>
      </header>`;
  const main = page.hub
    ? `      <ul class="link-list wide">
${c.items.map(([href, name, text]) => `        <li><a href="${p(href)}">${esc(name)}</a><p>${esc(text)}</p></li>`).join("\n")}
      </ul>
      ${c.after(p)}`
    : c.body(p).replace(/^\n/, "");
  const updated = page.updated && !page.hub ? `\n      <p class="note">${lang === "zh" ? `最後更新：${page.updated}。` : `Last updated ${page.updated}.`}</p>` : "";
  const jsonld = page.updated
    ? [{ "@context": "https://schema.org", "@type": "Article", headline: c.h1, description: c.description, inLanguage: ui.htmlLang, dateModified: page.updated, datePublished: page.updated, mainEntityOfPage: ORIGIN + p(page.path), author: { "@type": "Organization", name: "DappGo", url: ORIGIN + p("/about/") }, publisher: { "@type": "Organization", name: "DappGo", url: ORIGIN } }]
    : page.path === "/about/"
      ? [{ "@context": "https://schema.org", "@type": "Organization", name: "DappGo", url: ORIGIN, logo: `${ORIGIN}/icons/icon-512.png`, email: "admin@dappgo.com", founder: { "@type": "Person", name: "Yenlung Lai" }, address: { "@type": "PostalAddress", addressRegion: "CA", addressCountry: "US" }, sameAs: ["https://www.facebook.com/dappgo", "https://www.instagram.com/dappgo/", "https://www.threads.com/@dappgo", "https://www.linkedin.com/company/dappgo/"] }]
      : [];
  return renderPage({ lang, path: page.path, title: c.title, description: c.description, section: page.section, ads: page.ads, ogType: page.updated ? "article" : "website", crumbs, body: `${head}\n${main}${updated}`, jsonld, generator: "build-content.mjs" });
}

function sitemapEntry(enPath, lastmod, changefreq, priority) {
  return LANGS.map((lang) => `    <url>
        <loc>${ORIGIN}${localPath(lang, enPath)}</loc>
        <xhtml:link rel="alternate" hreflang="en" href="${ORIGIN}${enPath}" />
        <xhtml:link rel="alternate" hreflang="zh-Hant" href="${ORIGIN}${localPath("zh", enPath)}" />
        <xhtml:link rel="alternate" hreflang="x-default" href="${ORIGIN}${enPath}" />
        <lastmod>${lastmod}</lastmod>
        <changefreq>${changefreq}</changefreq>
        <priority>${priority}</priority>
    </url>`).join("\n");
}

export function renderAll(byMarket = loadRecords()) {
  const out = new Map();
  const sitemap = [];
  const newestDay = MARKETS.flatMap((m) => byMarket[m].map((r) => r.generated_at_utc.slice(0, 10))).sort().at(-1);
  if (MARKETS.every((m) => byMarket[m].length)) {
    for (const lang of LANGS) out.set(fileFor(lang, "/reports/"), renderHub(lang, byMarket));
    sitemap.push(sitemapEntry("/reports/", newestDay, "daily", "0.8"));
  }
  for (const market of MARKETS) {
    const records = byMarket[market];
    if (!records.length) continue;
    for (const lang of LANGS) out.set(fileFor(lang, `/reports/${market}/`), renderMarketIndex(lang, market, records));
    sitemap.push(sitemapEntry(`/reports/${market}/`, records.at(-1).generated_at_utc.slice(0, 10), "daily", "0.7"));
    records.forEach((record, i) => {
      const enPath = `/reports/${market}/${record.session_date}/`;
      for (const lang of LANGS) out.set(fileFor(lang, enPath), renderDay(lang, record, records[i - 1] || null, records[i + 1] || null));
    });
    // Newest first, so crawlers meet fresh sessions early.
    for (const record of [...records].reverse()) sitemap.push(sitemapEntry(`/reports/${market}/${record.session_date}/`, record.generated_at_utc.slice(0, 10), "never", "0.5"));
  }
  for (const page of PAGES) {
    for (const lang of LANGS) out.set(fileFor(lang, page.path), guidePage(lang, page));
    sitemap.push(sitemapEntry(page.path, page.updated || "2026-11-18", "monthly", page.section === "guides" ? "0.7" : "0.5"));
  }
  return { pages: out, sitemapBlock: `${SITEMAP_START}\n${sitemap.join("\n")}\n${SITEMAP_END}` };
}

export function applySitemap(xml, block) {
  const start = xml.indexOf(SITEMAP_START);
  const end = xml.indexOf(SITEMAP_END);
  if (start !== -1 && end !== -1) return xml.slice(0, start) + block + xml.slice(end + SITEMAP_END.length);
  if (!xml.includes("</urlset>")) throw new Error("sitemap.xml has no </urlset>");
  return xml.replace("</urlset>", `${block}\n</urlset>`);
}

// Archive the latest published payload of each market. A payload replaces a stored session only when it is newer.
async function archiveLatest() {
  const { load } = await import("./lib/market-data.mjs");
  for (const market of MARKETS) {
    const { payload } = await load(market);
    const record = extract(market, payload);
    if (!record) throw new Error(`${market}: latest payload has no dated price history`);
    const file = path.join(root, "data/reports", market, `${record.session_date}.json`);
    const current = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : null;
    if (current && current.generated_at_utc >= record.generated_at_utc) {
      console.log(`${market}: ${record.session_date} already archived at ${current.generated_at_utc}`);
      continue;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify(record) + "\n");
    console.log(`${market}: archived ${record.session_date} (${record.generated_at_utc}, ${record.data_hash.slice(0, 12)})`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  if (process.argv.includes("--latest")) await archiveLatest();
  const { pages, sitemapBlock } = renderAll();
  let changed = 0;
  for (const [file, html] of pages) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === html) continue;
    if (check) throw new Error(`${path.relative(root, file)} is out of date; run node scripts/build-content.mjs`);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
    changed++;
  }
  // A session that no longer has a record (for example a repaired backfill) must not keep a stale page.
  for (const lang of LANGS) {
    for (const market of MARKETS) {
      const dir = path.join(root, localPath(lang, `/reports/${market}/`).slice(1));
      if (!fs.existsSync(dir)) continue;
      for (const name of fs.readdirSync(dir)) {
        if (!/^\d{4}-\d{2}-\d{2}$/.test(name) || pages.has(path.join(dir, name, "index.html"))) continue;
        if (check) throw new Error(`${path.relative(root, path.join(dir, name))} has no record in data/reports; run node scripts/build-content.mjs`);
        fs.rmSync(path.join(dir, name), { recursive: true });
        changed++;
      }
    }
  }
  const sitemapFile = path.join(root, "sitemap.xml");
  const xml = fs.readFileSync(sitemapFile, "utf8");
  const next = applySitemap(xml, sitemapBlock);
  if (next !== xml) {
    if (check) throw new Error("sitemap.xml content block is out of date; run node scripts/build-content.mjs");
    fs.writeFileSync(sitemapFile, next);
    changed++;
  }
  console.log(check ? `Content pages: check passed (${pages.size} pages).` : `Content pages: ${pages.size} rendered, ${changed} files written.`);
}
