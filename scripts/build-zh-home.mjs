#!/usr/bin/env node
// Generate the Traditional Chinese homepage from the English page and home.js dictionary.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { I18N, esc, renderPulseHtml } from "./lib/home-html.mjs";

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function translateHome(english, pulse, catalog) {
  const t = I18N.zh;
  const copy = (key) => {
    if (typeof t[key] !== "string") throw new Error(`Missing zh translation: ${key}`);
    return t[key];
  };
  let html = english.replace('<html lang="en">', '<html lang="zh-Hant">');
  html = html.replace(/(<([a-z][\w-]*)\b[^>]*\bdata-i18n="([^"]+)"[^>]*>)[\s\S]*?(<\/\2>)/g,
    (_, open, tag, key, close) => open + esc(copy(key)) + close);
  html = html.replace(/(<([a-z][\w-]*)\b[^>]*\bdata-i18n-html="([^"]+)"[^>]*>)[\s\S]*?(<\/\2>)/g,
    (_, open, tag, key, close) => open + copy(key) + close);
  html = html.replace(/<[^>]+data-i18n-(alt|aria-label)="[^"]+"[^>]*>/g, (tag) => {
    const [, attr, key] = tag.match(/data-i18n-(alt|aria-label)="([^"]+)"/);
    return tag.replace(new RegExp(`(?<![\\w-])${attr}="[^"]*"`), `${attr}="${esc(copy(key))}"`);
  });
  html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-zh-home.mjs; edit index.html and the home.js dictionary. -->');
  html = html.replace(/<meta\b[^>]+(?:name|property)="(?:og:image:alt|twitter:image:alt)"[^>]*>/g, (tag) =>
    tag.replace(/content="[^"]*"/, `content="${esc(t.ogImageAlt)}"`));
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${esc(t.pageTitle)}</title>`);
  html = html.replace(/<meta\b[^>]+(?:name|property)="(?:description|og:title|og:description|twitter:title|twitter:description)"[^>]*>/g, (tag) =>
    tag.replace(/content="[^"]*"/, `content="${esc(/(?:og:|twitter:)title/.test(tag) ? t.pageTitle : t.pageDescription)}"`));
  html = html.replace('<link rel="canonical" href="https://dappgo.com/"', '<link rel="canonical" href="https://dappgo.com/zh/"');
  html = html.replace('<meta property="og:url" content="https://dappgo.com/"', '<meta property="og:url" content="https://dappgo.com/zh/"');
  html = html.replace('property="og:locale" content="en_US"', 'property="og:locale" content="zh_TW"')
    .replace('property="og:locale:alternate" content="zh_TW"', 'property="og:locale:alternate" content="en_US"');
  html = html.replace(/(<a class="lang" )[^>]*>[\s\S]*?<\/a>/,
    `$1href="/" data-lang-toggle hreflang="en" lang="en" aria-label="${esc(t.switchLanguage)}">${esc(t.languageName)}</a>`);
  return renderPulseHtml(html, pulse, "zh", catalog);
}

export function writeOrCheck(file, expected, check) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === expected) return false;
  if (check) throw new Error(`${path.relative(root, file)} is out of date; run node scripts/render-pulse-html.mjs`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, expected);
  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pulse = JSON.parse(fs.readFileSync(path.join(root, "data/pulse.json"), "utf8"));
  const catalog = JSON.parse(fs.readFileSync(path.join(root, "config/product-catalog.json"), "utf8"));
  const english = fs.readFileSync(path.join(root, "index.html"), "utf8");
  writeOrCheck(path.join(root, "zh/index.html"), translateHome(english, pulse, catalog), process.argv.includes("--check"));
  console.log(`Traditional Chinese homepage ${process.argv.includes("--check") ? "check passed" : "generated"}.`);
}
