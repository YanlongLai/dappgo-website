import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../assets/news-data.js', import.meta.url), 'utf8'), context);
const { analysis, localizedNews, plainAnalysis } = context.DappGoNewsData;
assert.equal(plainAnalysis('**台積電創天價** [[pos:營收成長]]'), '台積電創天價 營收成長');
assert.equal(plainAnalysis('<script>bad</script>'), '<script>bad</script>'); // Renderer escapes, never parses provider HTML.
const payload = { ai_commentary: '市場解析', ai_commentary_en: 'Market analysis', ticker_data: { AAPL: { news_commentary: '個股解析', news_commentary_en_summary: 'Company analysis', news_commentary_en_highlights: ['First fact'] }, EMPTY: {} } };
assert.equal(analysis(payload, 'all', 'zh').summary, '市場解析');
assert.equal(analysis(payload, 'all', 'en').summary, 'Market analysis');
assert.equal(analysis(payload, 'AAPL', 'zh'), null);
assert.equal(analysis(payload, 'AAPL', 'en'), null);
assert.equal(analysis(payload, 'EMPTY', 'zh'), null);
assert.equal(analysis(payload, 'MISSING', 'en'), null);
assert.equal(analysis({ ai_commentary: '中文' }, 'all', 'en'), null);
const mapped = { ai_commentary: { summary: '綜合解析', '2330': '台積電解析' }, ai_commentary_en: { summary: 'Market', '2330': 'TSMC' }, ticker_data: { '2330': {} } };
assert.equal(analysis(mapped, 'all', 'zh').summary, '綜合解析');
assert.equal(analysis(mapped, '2330', 'zh').summary, '台積電解析');
assert.equal(analysis(mapped, '2330', 'en').summary, 'TSMC');
assert.equal(analysis({ ...mapped, ai_commentary: { '2330': '台積電' } }, 'all', 'zh'), null);
assert.equal(analysis({ ...mapped, ai_commentary_summary: '精簡市場觀點', ai_commentary_summary_en: 'Concise market view' }, 'all', 'zh').summary, '精簡市場觀點');
assert.equal(analysis({ ...mapped, ai_commentary_summary: '精簡市場觀點', ai_commentary_summary_en: 'Concise market view' }, 'all', 'en').summary, 'Concise market view');
assert.equal(analysis({ ...mapped, ai_commentary_en: { summary: 'First paragraph.\n\nLong second paragraph.' } }, 'all', 'en').summary, 'First paragraph.');
assert.equal(analysis({ ticker_data: { ABC: { news_commentary_en: 'Yahoo: ABC shares fall after earnings; Reuters: guidance cut' } } }, 'ABC', 'en'), null);
const currentUs = { ai_commentary: { summary: '以下僅為輸入觀察的條件式解讀', GOOG: 'GOOG 輸入觀察：close_usd=$335.81；收盤低於 MA20。' }, ai_commentary_en: { GOOG: 'GOOG input observations: close_usd=$335.81; price is below MA20.' }, ticker_data: { GOOG: { news_ai_quality: { status: 'accepted' }, news_commentary: 'GOOG 新聞來源摘錄：\nYahoo: 「Headline」\n條件式觀察: 等待披露', news_commentary_summary: 'GOOG 條件式觀察: 等待披露', news_commentary_highlights: ['應先對照公司披露'], news_commentary_en: 'GOOG source quotations:\nYahoo: 「Headline」', news_commentary_en_summary: 'GOOG conditional watchpoints: wait for disclosures' } } };
assert.equal(analysis(currentUs, 'GOOG', 'zh').summary, currentUs.ai_commentary.GOOG);
assert.equal(analysis(currentUs, 'GOOG', 'en').summary, currentUs.ai_commentary_en.GOOG);
assert.equal(analysis(currentUs, 'GOOG', 'zh').highlights.length, 0);
assert.equal(analysis(currentUs, 'GOOG', 'zh').context, 'Yahoo: 「Headline」');
assert.equal(analysis(currentUs, 'GOOG', 'en').context, 'Yahoo: 「Headline」');
const richerUs = structuredClone(currentUs);
richerUs.ticker_data.GOOG.news_commentary_summary = 'GOOG 相關報導：Yahoo（2026-10-16）「公司宣布新產品」。此為來源說法，尚未獨立核實。';
richerUs.ticker_data.GOOG.news_commentary_primary_url = 'https://example.test/company-report';
assert.equal(analysis(richerUs, 'GOOG', 'zh').context, richerUs.ticker_data.GOOG.news_commentary_summary);
assert.equal(analysis(richerUs, 'GOOG', 'zh').contextUrl, 'https://example.test/company-report');
const unacceptedUs = structuredClone(currentUs);
unacceptedUs.ticker_data.GOOG.news_ai_quality.status = 'rejected';
assert.equal(analysis(unacceptedUs, 'GOOG', 'zh').context, '');
const irrelevantUs = structuredClone(currentUs);
irrelevantUs.ticker_data.GOOG.news_commentary_summary = '';
assert.equal(analysis(irrelevantUs, 'GOOG', 'zh').context, '');
assert.equal(analysis(currentUs, 'all', 'zh'), null);
assert.equal(analysis({ ...currentUs, ai_commentary: {} }, 'GOOG', 'zh'), null);
assert.equal(analysis({ ...currentUs, ai_commentary_en: {} }, 'GOOG', 'en'), null);
assert.equal(analysis({ ai_commentary: { GOOG: '量化資料已完成；模型說明暫時不可用' }, ticker_data: { GOOG: {} } }, 'GOOG', 'zh'), null);
assert.equal(analysis({ ai_commentary_en: { GOOG: 'GOOG: only close_usd is available; these inputs are insufficient for a directional company view.' }, ticker_data: { GOOG: {} } }, 'GOOG', 'en'), null);
assert.equal(localizedNews({ title: 'Original', title_zh: '中文標題', summary_zh: '中文摘要' }, 'zh').title, '中文標題');
assert.equal(localizedNews({ title: 'Original', title_zh: '' }, 'zh').title, 'Original');
assert.equal(localizedNews({ title: '中文', title_en: 'English' }, 'en').title, 'English');
console.log('Locale and scope selectors: passed');
